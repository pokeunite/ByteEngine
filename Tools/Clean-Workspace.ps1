<#
.SYNOPSIS
    Lists or removes generated ByteEngine build output.

.DESCRIPTION
    Reclaims disk space without touching authored content. Only a fixed list of
    well-known generated directories and diagnostic files is considered; user
    projects (Projects, Samples, Example, Sandbox, Plugins, PluginLibrary,
    Resources, MannequinCharacter, PublicPvpLobby, _ByteEngineD1) are never
    removed.

    The script is a dry run unless -Apply is supplied. Every path is resolved
    relative to the repository root and must remain inside it.

.PARAMETER Apply
    Actually delete the generated paths. Without this switch the script only
    reports what it would remove.

.PARAMETER IncludeBinObj
    Also remove every bin/ and obj/ directory in the tree. Slower, but useful
    before archiving a checkout. Defaults to on when -Apply is used with
    -Full, and off otherwise.

.PARAMETER Full
    Shorthand for -IncludeBinObj plus the generated root folders.

.EXAMPLE
    powershell -ep bypass -file .\Tools\Clean-Workspace.ps1

.EXAMPLE
    powershell -ep bypass -file .\Tools\Clean-Workspace.ps1 -Apply
#>
[CmdletBinding()]
param(
    [switch]$Apply,
    [switch]$IncludeBinObj,
    [switch]$Full
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

$root = [IO.Path]::GetFullPath((Split-Path -Parent $PSScriptRoot))
if (-not (Test-Path -LiteralPath (Join-Path $root 'ByteEngine.sln'))) {
    throw "Clean-Workspace must live in a ByteEngine checkout (missing ByteEngine.sln in $root)."
}

if ($Full) {
    $IncludeBinObj = $true
}

# Generated directories that may be recreated at any time. Keep this list
# deliberately narrow so authored projects and sample content are never hit.
$generatedDirectories = @(
    '.artifacts'
    'artifacts'
    'Dist'
    'Backups'
    'UpdateBackups'
    'output'
    'tmp'
    'node_modules'
    '__pycache__'
)

# Generated diagnostic files at the repository root. These are covered by
# .gitignore and safe to drop.
$generatedFiles = @(
    'engine_startup_error.txt'
    'parts-before-cleanup.csv'
    'parts-removed.txt'
)

function Get-RelativePath([string]$path) {
    $rootFull = $root.TrimEnd('\', '/') + [IO.Path]::DirectorySeparatorChar
    $full = [IO.Path]::GetFullPath($path)
    if ($full.StartsWith($rootFull, [StringComparison]::OrdinalIgnoreCase)) {
        return $full.Substring($rootFull.Length)
    }
    return $full
}

function Test-InsideRoot([string]$path) {
    $full = [IO.Path]::GetFullPath($path)
    return $full.StartsWith($root + [IO.Path]::DirectorySeparatorChar, [StringComparison]::OrdinalIgnoreCase) -or
        $full.Equals($root, [StringComparison]::OrdinalIgnoreCase)
}

$targets = [System.Collections.Generic.List[string]]::new()

foreach ($name in $generatedDirectories) {
    $path = Join-Path $root $name
    if (Test-Path -LiteralPath $path -PathType Container) {
        $targets.Add($path)
    }
}

foreach ($name in $generatedFiles) {
    $path = Join-Path $root $name
    if (Test-Path -LiteralPath $path -PathType Leaf) {
        $targets.Add($path)
    }
}

if ($IncludeBinObj) {
    $coveredAtStart = $targets.ToArray()
    $buildDirectories = @(Get-ChildItem -LiteralPath $root -Directory -Recurse -Force -ErrorAction SilentlyContinue |
        Where-Object { $_.Name -in @('bin', 'obj') })
    foreach ($directory in $buildDirectories) {
        # Never follow into a generated folder we already intend to remove.
        $alreadyCovered = $false
        foreach ($covered in $coveredAtStart) {
            if ($directory.FullName.StartsWith($covered + [IO.Path]::DirectorySeparatorChar, [StringComparison]::OrdinalIgnoreCase)) {
                $alreadyCovered = $true
                break
            }
        }
        if (-not $alreadyCovered) {
            $targets.Add($directory.FullName)
        }
    }
}

$targets = $targets | Sort-Object -Unique

if ($targets.Count -eq 0) {
    Write-Host 'Nothing to clean. The working tree already contains only authored content.'
    return
}

$totalBytes = 0L
foreach ($target in $targets) {
    if (-not (Test-InsideRoot $target)) {
        throw "Refusing to touch a path outside the repository: $target"
    }

    if (Test-Path -LiteralPath $target -PathType Container) {
        $files = @(Get-ChildItem -LiteralPath $target -Recurse -File -Force -ErrorAction SilentlyContinue)
        $bytes = ($files | Measure-Object Length -Sum).Sum
        if ($null -eq $bytes) { $bytes = 0 }
        $totalBytes += $bytes
        Write-Host ('{0,-10} {1,10:N1} MB  {2}' -f 'directory', ($bytes / 1MB), (Get-RelativePath $target))
    }
    else {
        $bytes = (Get-Item -LiteralPath $target).Length
        $totalBytes += $bytes
        Write-Host ('{0,-10} {1,10:N1} MB  {2}' -f 'file', ($bytes / 1MB), (Get-RelativePath $target))
    }
}

Write-Host ('Total reclaimable: {0:N1} MB across {1} path(s).' -f ($totalBytes / 1MB), $targets.Count)

if (-not $Apply) {
    Write-Host 'Dry run. Re-run with -Apply to remove these generated paths.'
    return
}

if (Get-Process -Name 'ByteEngine.Editor', 'ByteEngine' -ErrorAction SilentlyContinue) {
    throw 'Close ByteEngine before cleaning. No files were removed.'
}

$removed = 0
foreach ($target in $targets) {
    if (-not (Test-Path -LiteralPath $target)) { continue }
    Remove-Item -LiteralPath $target -Recurse -Force
    $removed++
}

Write-Host ("Removed {0} generated path(s). Authored content was left untouched." -f $removed)
