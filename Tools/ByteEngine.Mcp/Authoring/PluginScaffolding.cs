using System.Text.Json;

namespace ByteEngine.Mcp.Authoring;

/// <summary>Text templates for a minimal, buildable ByteEngine gameplay plugin.</summary>
internal static class PluginScaffolding
{
    private static readonly JsonSerializerOptions ManifestJson = new() { WriteIndented = true };

    public static string CSharpProject(string name, string namespaceName) => $"""
<Project Sdk="Microsoft.NET.Sdk">
  <PropertyGroup>
    <TargetFramework>net9.0</TargetFramework>
    <ImplicitUsings>enable</ImplicitUsings>
    <Nullable>enable</Nullable>
    <AssemblyName>{name}.Plugin</AssemblyName>
    <RootNamespace>{namespaceName}</RootNamespace>
    <BytePluginName>{name}</BytePluginName>
  </PropertyGroup>
  <ItemGroup>
    <ProjectReference Include="../../Engine/ByteEngine.Core/ByteEngine.Core.csproj" Private="false" />
  </ItemGroup>
  <Import Project="../BytePlugin.targets" />
</Project>
""";

    public static string Manifest(string id, string name, string namespaceName) => JsonSerializer.Serialize(new
    {
        schemaVersion = 1,
        id,
        name,
        version = "0.1.0",
        assembly = name + ".Plugin.dll",
        entryPoint = namespaceName + "." + name + "Plugin",
        editor = true,
        runtime = true,
        minimumEngineVersion = ByteEngine.Core.ByteEngineInfo.Version,
        dependencies = Array.Empty<object>()
    }, ManifestJson);

    public static string ComponentSource(string name, string namespaceName, string component) => $$"""
using ByteEngine.Core.Plugins;
using ByteEngine.Core.Scene;

namespace {{namespaceName}};

public sealed class {{name}}Plugin : IByteEnginePlugin
{
    public void Register(ByteEnginePluginContext context)
    {
        context.RegisterSimpleComponent<{{component}}>(
            "{{component}}",
            new ByteEnginePluginComponentMetadata(
                DisplayName: "{{component}}",
                Category: "Gameplay",
                Description: "Gameplay component added by the {{name}} plugin.",
                SearchKeywords: "{{name.ToLowerInvariant()}} gameplay"));
    }
}

public sealed class {{component}} : Component
{
    public float Speed { get; set; } = 1f;

    protected override void OnStart()
    {
    }

    protected override void OnUpdate()
    {
    }
}
""";

    public static string Readme(string name, string id, string component) => $$"""
# {{name}} plugin

Generated by the ByteEngine MCP authoring server.

- Source: `Plugins/{{name}}/{{name}}Plugin.cs`
- Component: `{{component}}` (codec id `{{id}}.{{component}}`)
- Manifest id: `{{id}}`

Build the package from the engine repository:

```powershell
dotnet build Plugins/{{name}}/{{name}}.Plugin.csproj -c Release
```

The build writes `artifacts/plugins/{{name}}.byteplugin`. Using MCP instead:

```json
{"plugin":"{{name}}","install":true}
```

`be_plugin(op:"build")` compiles and packages; `install:true` copies the package
into the active project and requires reopening the project so the assembly can
register its components and Event Sheet nodes.
""";
}
